// Proximity sorting helper
export function sortProvidersByProximity(
  providers: Provider[],
  selectedTown: string
): Provider[] {
  return [...providers].sort((a, b) => {
    // 1. Exact match in selected town first
    const aInTown = a.town.toLowerCase() === selectedTown.toLowerCase();
    const bInTown = b.town.toLowerCase() === selectedTown.toLowerCase();
    if (aInTown && !bInTown) return -1;
    if (!aInTown && bInTown) return 1;

    // 2. Serves selected town second
    const aServes = a.servesAreas.some((t) => t.toLowerCase() === selectedTown.toLowerCase());
    const bServes = b.servesAreas.some((t) => t.toLowerCase() === selectedTown.toLowerCase());
    if (aServes && !bServes) return -1;
    if (!aServes && bServes) return 1;

    // 3. Estimated distance
    const distA = getEstimatedDistance(selectedTown, a.town);
    const distB = getEstimatedDistance(selectedTown, b.town);
    if (distA !== distB) return distA - distB;

    // 4. Rating
    return b.rating - a.rating;
  });
}

