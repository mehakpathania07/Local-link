export function getEstimatedDistance(fromTown: string, toTown: string): number {
  const normFrom = fromTown.trim();
  const normTo = toTown.trim();
  if (normFrom === normTo) return 0.8;
  if (DISTANCE_MATRIX[normFrom] && DISTANCE_MATRIX[normFrom][normTo] !== undefined) {
    return DISTANCE_MATRIX[normFrom][normTo];
  }
  if (DISTANCE_MATRIX[normTo] && DISTANCE_MATRIX[normTo][normFrom] !== undefined) {
    return DISTANCE_MATRIX[normTo][normFrom];
  }
  return 8.5; // fallback average distance
}

